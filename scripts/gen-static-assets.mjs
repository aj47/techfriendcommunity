// Regenerates convex/staticAssets.generated.ts from dist/ so the built SPA can be
// served by a Convex HTTP action, giving the app a *.convex.site URL with no
// separate static host. Run after `npm run build`.
import { readFileSync, readdirSync, statSync, writeFileSync } from "fs";
import { join, relative, extname } from "path";

const DIST = "dist";
const OUT = "convex/staticAssets.generated.ts";

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".json": "application/json; charset=utf-8",
  ".png": "image/png",
  ".ico": "image/x-icon",
  ".txt": "text/plain; charset=utf-8",
};

function walk(dir) {
  let out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out = out.concat(walk(p));
    else out.push(p);
  }
  return out;
}

const files = walk(DIST);
const entries = files.map((p) => {
  const urlPath = "/" + relative(DIST, p).split("\\").join("/");
  const ext = extname(p);
  const contentType = TYPES[ext] ?? "application/octet-stream";
  const b64 = readFileSync(p).toString("base64");
  const cache = urlPath.startsWith("/assets/") ? "public, max-age=31536000, immutable" : "public, max-age=60";
  return { urlPath, contentType, cache, b64 };
});

const body = `// GENERATED by scripts/gen-static-assets.mjs — do not edit by hand.
// Regenerate with: npm run build && node scripts/gen-static-assets.mjs
export type StaticAsset = { contentType: string; cache: string; base64: string };
export const staticAssets: Record<string, StaticAsset> = {
${entries.map((e) => `  ${JSON.stringify(e.urlPath)}: { contentType: ${JSON.stringify(e.contentType)}, cache: ${JSON.stringify(e.cache)}, base64: ${JSON.stringify(e.b64)} },`).join("\n")}
};
export const indexHtml = staticAssets["/index.html"];
`;
writeFileSync(OUT, body);
console.log(`wrote ${OUT}: ${entries.length} assets, ${(body.length / 1024).toFixed(0)} KB`);
