// Regenerates convex/ogRuntime.generated.ts: the resvg WebAssembly binary and
// the Inter subsets the dynamic link-preview cards are rasterized with, both
// base64-inlined so the Convex deployment carries its own renderer and needs no
// outbound fetch (and no CDN) on a cold start.
//
// The output is committed. Re-run it only when @resvg/resvg-wasm is upgraded or
// the card needs a glyph the subset doesn't have:
//
//   npm i && pip install --break-system-packages fonttools brotli
//   sudo apt-get install -y fonts-inter
//   node scripts/gen-og-runtime.mjs
import { execFileSync } from "child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "fs";
import { tmpdir } from "os";
import { join } from "path";

const WASM = "node_modules/@resvg/resvg-wasm/index_bg.wasm";
const FONT_DIR = "/usr/share/fonts/opentype/inter";
const OUT = "convex/ogRuntime.generated.ts";

// The card sets body copy in Inter and the wordmark in Inter Display; resvg
// matches on the family and weight in each file's name table, so every weight
// the SVG asks for needs its own file. Keep this in sync with card.ts.
const FONTS = ["Inter-Regular", "Inter-Medium", "Inter-SemiBold", "InterDisplay-SemiBold"];

// Latin, Latin-1, the punctuation Discord messages actually contain (curly
// quotes, dashes, ellipsis, bullets) and a few arrows. Everything outside this
// is stripped from card text before rendering — see sanitize() in card.ts —
// because a missing glyph renders as nothing at all.
const UNICODES = [
  "U+0020-007E", "U+00A0-00FF", "U+2010-2027", "U+2030-2044",
  "U+20AC", "U+2122", "U+2190-2193", "U+2713", "U+25CF",
].join(",");

// Emits { codepoint: advance in 1/1000 em } for a subset file, read back by the
// card layout. fontTools is already a prerequisite here for the subsetting.
const WIDTHS_PY = `
import json, sys
from fontTools.ttLib import TTFont
f = TTFont(sys.argv[1])
upem = f["head"].unitsPerEm
hmtx = f["hmtx"]
out = {}
for cp, glyph in f.getBestCmap().items():
    out[cp] = round(hmtx[glyph][0] * 1000 / upem)
json.dump(out, sys.stdout)
`;

const tmp = mkdtempSync(join(tmpdir(), "og-fonts-"));
try {
  const fonts = FONTS.map((name) => {
    const out = join(tmp, `${name}.otf`);
    execFileSync("pyftsubset", [
      join(FONT_DIR, `${name}.otf`),
      `--unicodes=${UNICODES}`,
      "--layout-features=kern,liga,calt",
      "--no-hinting",
      `--output-file=${out}`,
    ]);
    // resvg can't measure text for us, so the card wraps and truncates against
    // these advance widths (1/1000 em, kerning ignored — it rounds long).
    const widths = JSON.parse(
      execFileSync("python3", ["-c", WIDTHS_PY, out], { encoding: "utf8" }),
    );
    return { name, base64: readFileSync(out).toString("base64"), widths };
  });
  const wasm = readFileSync(WASM).toString("base64");

  const body = `// GENERATED by scripts/gen-og-runtime.mjs — do not edit by hand.
// resvg's WebAssembly binary plus the Inter subsets the link-preview cards are
// set in, base64 so they ship inside the Convex module.
export const resvgWasmBase64 = ${JSON.stringify(wasm)};
export const fontsBase64: string[] = [
${fonts.map((f) => `  // ${f.name}\n  ${JSON.stringify(f.base64)},`).join("\n")}
];
// Advance widths in 1/1000 em, keyed by codepoint, one table per font above.
export const fontWidths: Record<string, Record<string, number>> = {
${fonts.map((f) => `  ${JSON.stringify(f.name)}: ${JSON.stringify(f.widths)},`).join("\n")}
};
`;
  writeFileSync(OUT, body);
  const kb = (n) => `${(n / 1024).toFixed(0)} KB`;
  console.log(
    `wrote ${OUT}: wasm ${kb(wasm.length)} base64, ${fonts.length} fonts ${kb(fonts.reduce((n, f) => n + f.base64.length, 0))} base64`,
  );
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
